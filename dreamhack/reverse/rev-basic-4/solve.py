byte = [
    0x24, 0x27, 0x13, 0xc6, 0xc6, 0x13, 0x16, 0xe6, 0x47, 0xf5,
    0x26, 0x96, 0x47, 0xf5, 0x46, 0x27, 0x13, 0x26, 0x26, 0xc6,
    0x56, 0xf5, 0xc3, 0xc3, 0xf5, 0xe3, 0xe3, 0x00,
]

def rol(x, y):
    shl = (x << y) & 0xff
    carry = (x >> (8 - y)) & 0xff
    carry &= 0xff
    return (shl | carry) & 0xff

res = []
for b in byte:
    res.append(rol(b, 4))

for i in res:
    print(chr(i), end='')

